"""Render the generated documents from templates and committed results.

Template syntax (inside ``docs_templates/*.md``):

* ``{{ results/path.json#a.b.0.c | .3f }}`` - a value from a results file, formatted
  with a Python format spec. Append ``| pct`` to show a fraction as a percentage and
  ``| M`` (one decimal) or ``| M2`` to show a count in millions. Keys
  containing dots go in brackets: ``#files.[val/x.parquet].sha256``.
* ``{{ table:name }}`` - a Markdown table produced by ``tsfm.docs.tables.TABLES[name]``.
* ``{{ ... | default:text }}`` - text to show if the results file does not exist yet.
* A block that depends on whether a results file exists, with each tag on its own line
  (the ``{{ else }}`` part is optional; blocks do not nest)::

      {{ if exists:results/path.json }}
      lines shown once the file exists
      {{ else }}
      lines shown until then
      {{ end }}

Placeholders inside fenced or inline code are rejected, so code samples can only hold
hand-written static text (which the number guard then skips).
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

from tsfm.docs.numbers import _FENCE_RE, _INLINE_CODE_RE
from tsfm.paths import repo_root

TEMPLATE_DIR = "docs_templates"
OUTPUTS = {
    "README.md": "README.md",
    "DATA_CARD.md": "DATA_CARD.md",
    "MODEL_CARD.md": "MODEL_CARD.md",
    "RESEARCH_NOTE.md": "RESEARCH_NOTE.md",
}
HEADER = "<!-- GENERATED by `tsfm docs build` from {src}. Do not edit by hand. -->\n"

_PLACEHOLDER_RE = re.compile(r"\{\{\s*(.*?)\s*\}\}", re.S)
_IF_RE = re.compile(
    r"^\{\{[ \t]*if exists:(\S+?)[ \t]*\}\}\n(.*?)"
    r"(?:^\{\{[ \t]*else[ \t]*\}\}\n(.*?))?"
    r"^\{\{[ \t]*end[ \t]*\}\}(?:\n|\Z)",
    re.S | re.M,
)
_KEY_RE = re.compile(r"\[([^\]]+)\]|([^.\[\]]+)")


class MissingResult(KeyError):
    pass


def lookup(root: Path, ref: str) -> Any:
    file, _, keypath = ref.partition("#")
    path = root / file
    if not path.exists():
        raise MissingResult(file)
    obj: Any = json.loads(path.read_text())
    # Keys are dot-separated; use [brackets] for keys containing dots or slashes.
    for key in (m.group(1) or m.group(2) for m in _KEY_RE.finditer(keypath)):
        if isinstance(obj, list):
            obj = obj[int(key)]
        else:
            if key not in obj:
                raise KeyError(f"{key!r} not in {file}#{keypath}")
            obj = obj[key]
    return obj


def _format(value: Any, spec: str) -> str:
    if spec == "pct":
        return f"{100 * float(value):.1f}%"
    if spec.startswith("pct"):
        return f"{100 * float(value):.{int(spec[3:])}f}%"
    if spec in ("", "str"):
        return str(value)
    if spec == "int":
        return f"{int(value):,}"
    if spec in ("M", "M1", "M2"):  # millions, e.g. 10083392 -> "10.1M"
        return f"{float(value) / 1e6:.{int(spec[1:] or 1)}f}M"
    return format(value, spec)


def render_placeholder(expr: str, root: Path) -> str:
    parts = [p.strip() for p in expr.split("|")]
    head, filters = parts[0], parts[1:]
    default = next((f.split(":", 1)[1] for f in filters if f.startswith("default:")), None)
    filters = [f for f in filters if not f.startswith("default:")]
    try:
        if head.startswith("table:"):
            from tsfm.docs.tables import TABLES

            return TABLES[head.removeprefix("table:")](root)
        value = lookup(root, head)
    except MissingResult:
        if default is None:
            raise
        return default
    return _format(value, filters[0] if filters else "")


def render(template: str, root: Path) -> str:
    for rx in (_FENCE_RE, _INLINE_CODE_RE):
        for m in rx.finditer(template):
            if "{{" in m.group(0):
                raise ValueError(f"placeholder inside code is not allowed: {m.group(0)[:80]!r}")
    template = _IF_RE.sub(
        lambda m: m.group(2) if (root / m.group(1)).exists() else (m.group(3) or ""), template
    )
    return _PLACEHOLDER_RE.sub(lambda m: render_placeholder(m.group(1), root), template)


def _sync(path: Path, text: str, rel: str, *, check: bool, stale: list[str]) -> None:
    if check:
        if not path.exists() or path.read_text() != text:
            stale.append(rel)
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)


def build(root: Path | None = None, *, check: bool = False) -> list[str]:
    """Render documents and figures. With ``check=True``, return the stale output paths."""
    root = root or repo_root()
    stale: list[str] = []
    for tpl_name, out_name in OUTPUTS.items():
        tpl = root / TEMPLATE_DIR / tpl_name
        if not tpl.exists():
            continue
        text = HEADER.format(src=f"{TEMPLATE_DIR}/{tpl_name}") + render(tpl.read_text(), root)
        _sync(root / out_name, text, out_name, check=check, stale=stale)
    # Imported lazily: figure drawing is independent of the template language.
    from tsfm.docs.figures import figure_svgs

    for rel, text in figure_svgs(root).items():
        _sync(root / rel, text, rel, check=check, stale=stale)
    return stale
